import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {runFileProgram,projectCSV} from '../dist/file-program.mjs';
import {portableZip} from '../dist/portable-export.mjs';
const home=new URL('../examples/sql-validation/',import.meta.url);await mkdir(home,{recursive:true});
const source=`data sql_a;length g $4;id=1;g='A';x=2;output;id=1;x=4;output;id=2;g='B';x=8;output;id=.;g='';x=.;output;run;
data sql_b;id=1;y=3;output;id=1;y=6;output;id=3;y=12;output;id=.;y=9;output;run;`;
const cases=[];
for(const join of ['inner','left','right','full'])cases.push([`sql_${join}`,`select a.id as left_id,b.id as right_id,a.x,b.y from sql_a as a ${join} join sql_b as b on a.id=b.id order by left_id,x,y`]);
cases.push(
 ['sql_cross','select a.id as aid,b.id as bid,a.x,b.y from sql_a as a cross join sql_b as b order by aid,bid,x,y'],
 ['sql_grouped','select g,count(*) as rows_count,count(x) as nonmissing,count(distinct id) as unique_ids,sum(x) as total,mean(x) as average,avg(x) as average2,std(x) as sd,stddev(x) as sd2,var(x) as variance,min(x) as lo,max(x) as hi from sql_a group by g order by g'],
 ['sql_row_functions',"select id,x,mean(x,10) as row_mean,sum(x,10) as row_sum,put(coalesce(x,0),z4.) as text,input('0042',4.) as parsed from sql_a order by id,x"],
 ['sql_calculated',"select id,x*2 as doubled,calculated doubled+1 as adjusted,case g when 'A' then 'alpha' else 'other' end as label from sql_a where calculated doubled>=8 order by adjusted desc"],
 ['sql_distinct','select distinct g from sql_a order by g'],
 ['sql_unique','select unique g from sql_a order by g desc'],
 ['sql_group_order','select g,x from sql_a group by g,x'],
 ['sql_having','select g,count(*) as rows_count,mean(x) as average from sql_a group by g having calculated rows_count>1 order by g'],
 ['sql_case_group','select case when x is missing then 0 when x>3 then 1 else 2 end as bin,count(*) as rows_count from sql_a group by calculated bin order by bin'],
 ['sql_empty','select count(*) as rows_count,sum(x) as total,mean(x) as average,std(x) as sd from sql_a where id=99'],
 ['sql_missing','select id,x from sql_a where id in (1,.) and x between . and 4 order by id,x'],
 ['sql_composite','select a.id as aid,a.x,b.y from sql_a as a left join sql_b as b on a.id=b.id and b.y>3 order by aid,x,y']
);
let program=`/* SAS ONLY: run this entire file in SAS Studio, without CSV uploads or path edits.
   Expected values generated by Sassy v0.4.20; not previously certified by SAS.
   Numeric criterion: relative 1e-10; character values compared too.
   Original row order and exact metadata/layout are not certified by sorted comparisons.
   sql_group_order intentionally exercises SAS GROUP BY-to-ORDER BY behavior and
   may produce its documented WARNING. Return Results and Log. */
%macro sql_check(base,expected);
 %if %sysfunc(exist(&base))=0 or %sysfunc(exist(&expected))=0 %then %do;
  %put ERROR: SQL comparison did not run because &base or &expected is missing.;
  %return;
 %end;
 proc sort data=&base out=sas_sql_check; by _all_; run;
 proc sort data=&expected out=app_sql_check; by _all_; run;
 title "SQL values: &base versus &expected";
 proc compare base=sas_sql_check compare=app_sql_check method=relative criterion=1e-10; run;
%mend;
${source}
`;
const files={},manifest={appVersion:'0.4.20',actualSASValidation:'pending',criterion:{relative:1e-10},cases:[]};
for(const [name,select] of cases){
 const code=`proc sql;create table ${name} as ${select};quit;`,result=await runFileProgram(source+code),ds=result.datasets[name],expected='app_'+name,csv=projectCSV(ds);
 files[name+'.csv']=csv;files[name+'.sas']=source+'\n'+code+'\n';
 program+=`\n/* ${name} */\nproc datasets lib=work nolist;delete ${name} ${expected};quit;\n${code}\ndata ${expected}; length ${ds.columns.map(c=>c+' '+(ds.types[c]==='char'?'$128':'8')).join(' ')}; infile datalines4 dsd dlm=',' truncover; input ${ds.columns.map(c=>c+' :'+(ds.types[c]==='char'?'$128.':'best32.')).join(' ')};\ndatalines4;\n${csv.replace(/\r\n/g,'\n').split('\n').slice(1).join('\n')}\n;;;;\nrun;\n%sql_check(${name},${expected});\n`;
 manifest.cases.push({name,rows:ds.rows.length,columns:ds.columns,types:ds.types});
}
program+='title;\n';files['01-sas-sql-comparison.sas']=program;
files['README.md']=`# PROC SQL comparison — Sassy v0.4.20

Upload/run only 01-sas-sql-comparison.sas in SAS Studio. No CSV uploads, folders or edits are needed. Return Results and Log. Sixteen groups cover joins (including duplicate/missing keys), grouped statistics, DISTINCT/UNIQUE, CASE, CALCULATED, row functions, HAVING, empty summaries and missing predicates.

These are app-generated expectations awaiting actual SAS validation. Comparisons sort by all columns before matching values; original SQL row order and exact descriptors/layout are outside this certification. Relative numeric tolerance is 1e-10; character values are also compared. One GROUP BY-without-summary test may produce SAS's expected transformation warning. SQL remerging, subqueries, DML, set operations, views and macro INTO are deliberately unsupported. Original models/CSVs are reference material and need not be uploaded.
`;
files['manifest.json']=JSON.stringify(manifest,null,2)+'\n';
for(const [name,text] of Object.entries(files))await writeFile(new URL(name,home),text);
await writeFile(new URL('sql-validation.zip',home),portableZip(files));
console.log(`Packaged ${cases.length} self-contained SQL comparisons (${manifest.cases.reduce((n,c)=>n+c.rows,0)} rows); actual SAS run pending.`);
