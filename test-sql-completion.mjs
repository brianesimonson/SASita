import assert from 'node:assert/strict';
import {completionContext} from './dist/completion.mjs';
import {runFileProgram} from './dist/file-program.mjs';
const table={columns:['id','amount','provider'],types:{id:'num',amount:'num',provider:'char'}};
Object.defineProperty(table,'rows',{get(){throw new Error('SQL editor must not inspect observations');}});
const state={datasets:{claims:table},libraries:{saved:'tables'},members:{saved:['claims']},descriptors:{'saved.claims':table}};
const get=(code,caret=code.length)=>completionContext(code,caret,state);
assert.ok(get('proc sql').items.some(i=>i.label==='OUTOBS='));
assert.ok(!get('proc sql noprint ').items.some(i=>i.label==='NOPRINT'));
assert.ok(get('proc sql;??').items.some(i=>i.keyword==='create'));
assert.ok(get('proc sql;').items.some(i=>i.keyword==='select'));
assert.ok(get('proc sql;select * from saved.').items.some(i=>i.label==='saved.claims'));
let code='proc sql;select c.am from work.claims as c;quit;',at=code.indexOf('c.am')+4,c=get(code,at),choice=c.items.find(i=>i.label==='amount');
code=code.slice(0,c.start)+choice.insert+code.slice(c.end);assert.equal(code,'proc sql;select c.amount from work.claims as c;quit;');
const executed=await runFileProgram(code,{claims:{...table,rows:[{id:1,amount:42,provider:'A'}]}});assert.equal(executed.reports[0].dataset.rows[0].amount,42);
code='proc sql;select std( from saved.claims as c;';at=code.indexOf('std(')+4;assert.deepEqual(get(code,at).items.map(i=>i.label),['amount','id']);
code='proc sql;select a. from claims a left join saved.claims b on a.id=b.id;';at=code.indexOf('a.')+2;assert.ok(get(code,at).items.some(i=>i.label==='provider'));
for(const value of ['proc sql;select \'c.','proc sql;/* c.','proc sql;select unknown.'])assert.equal(get(value),null);
console.log('PROC SQL editor: metadata-only header/starters, native source names, qualified alias insertion and numeric summary fields passed.');
